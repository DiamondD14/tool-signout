// Builds the encrypted constants embedded in surplus.html.
//
//   node tools/build-surplus-vault.mjs <master.json> <employee-password> <admin-password> <helper-password> [comps.json]
//
// comps.json (optional) maps inventory id -> [usedLow, usedHigh, "source"].
// master.json is the DEFAULT_MASTER array from the field hub's kit-inventory page.
// It rewrites the VAULT block in surplus.html in place. Keep master.json out of the repo:
// it holds purchase prices in plain text and this repo is public.
//
// What gets encrypted:
//   HELPER_CHECK — proves the helper (assistant) password is right; helpers upload photos only
//   EMP_CHECK    — proves the employee password is right (AES-GCM, key = PBKDF2(employee password))
//   ADMIN_VAULT  — { employeePassword, rsaPrivateJwk, catalog } (AES-GCM, key = PBKDF2(admin password))
//   PUBLIC_KEY   — RSA-OAEP public key; public buyers' contact details are encrypted to it so
//                  only admin can read them.
import { readFileSync, writeFileSync } from "node:fs";
import { webcrypto as crypto } from "node:crypto";

const [, , masterPath, empPw, adminPw, helperPw, compsPath] = process.argv;
if (!masterPath || !empPw || !adminPw || !helperPw) {
  console.error("usage: node tools/build-surplus-vault.mjs <master.json> <employee-password> <admin-password> <helper-password> [comps.json]");
  process.exit(1);
}

const ITER = 150000;
const enc = new TextEncoder();
const b64 = buf => Buffer.from(buf).toString("base64");

async function deriveKey(password, salt) {
  const base = await crypto.subtle.importKey("raw", enc.encode(password), "PBKDF2", false, ["deriveKey"]);
  return crypto.subtle.deriveKey(
    { name: "PBKDF2", hash: "SHA-256", salt: enc.encode(salt), iterations: ITER },
    base, { name: "AES-GCM", length: 256 }, false, ["encrypt", "decrypt"]);
}
async function seal(key, obj) {
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ct = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, enc.encode(JSON.stringify(obj)));
  return b64(iv) + "." + b64(ct);
}

const master = JSON.parse(readFileSync(masterPath, "utf8"));
const comps = compsPath ? JSON.parse(readFileSync(compsPath, "utf8")) : {};
const KEEP = new Set(["equip", "tool", "winter", "ppe"]);
const catalog = master
  .filter(i => KEEP.has(i.cat) && i.unitPrice > 0)
  .map(i => {
    const c = comps[i.id];
    return { id: i.id, name: i.name.replace(/\s+/g, " ").trim(), cat: i.cat, paid: i.unitPrice, store: i.store,
      ...(c ? { compLow: c[0], compHigh: c[1], compSource: c[2] } : {}) };
  })
  .sort((a, b) => b.paid - a.paid);

const empKey = await deriveKey(empPw, "ener-surplus-employee-v1");
const adminKey = await deriveKey(adminPw, "ener-surplus-admin-v1");
const helperKey = await deriveKey(helperPw, "ener-surplus-helper-v1");

const rsa = await crypto.subtle.generateKey(
  { name: "RSA-OAEP", modulusLength: 2048, publicExponent: new Uint8Array([1, 0, 1]), hash: "SHA-256" },
  true, ["encrypt", "decrypt"]);
const publicJwk = await crypto.subtle.exportKey("jwk", rsa.publicKey);
const privateJwk = await crypto.subtle.exportKey("jwk", rsa.privateKey);

const out = `// ── VAULT (generated by tools/build-surplus-vault.mjs — do not edit by hand) ──
const KDF_ITER = ${ITER};
const HELPER_CHECK = ${JSON.stringify(await seal(helperKey, { ok: true }))};
const EMP_CHECK = ${JSON.stringify(await seal(empKey, { ok: true }))};
const ADMIN_VAULT = ${JSON.stringify(await seal(adminKey, { employeePassword: empPw, rsaPrivateJwk: privateJwk, catalog }))};
const PUBLIC_KEY = ${JSON.stringify({ kty: publicJwk.kty, n: publicJwk.n, e: publicJwk.e, alg: publicJwk.alg })};
// ── END VAULT ──`;
const pagePath = new URL("../surplus.html", import.meta.url);
const page = readFileSync(pagePath, "utf8");
const re = /\/\/ ── VAULT[\s\S]*?\/\/ ── END VAULT ──/;
if (!re.test(page)) { console.error("VAULT block not found in surplus.html"); process.exit(1); }
writeFileSync(pagePath, page.replace(re, () => out));
console.log(`surplus.html vault updated — catalog items: ${catalog.length}, with comps: ${catalog.filter(c => c.compLow != null).length}`);
